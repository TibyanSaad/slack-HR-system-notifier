-- adding another column to track which notifications have been sent to slack or not
ALTER TABLE notifications ADD sent_to_slack CHAR(1) DEFAULT 'N' NOT NULL
    CONSTRAINT ck_notifications_sent_to_slack CHECK (sent_to_slack IN ('Y','N'));

-- explicit cursor to make the attributes available
CREATE OR REPLACE PROCEDURE get_pending_notifications (
  p_cursor OUT SYS_REFCURSOR
) AS
BEGIN
OPEN p_cursor FOR
SELECT notification_id, type, message, created_at,
       number_of_applicants, job_id
FROM notifications
WHERE sent_to_slack = 'N'
ORDER BY created_at;
END get_pending_notifications;
/

-- procedure to set the sent_to_slack form 'N' TO 'Y'
CREATE OR REPLACE PROCEDURE mark_notification_sent (
  p_notification_id IN NUMBER
) AS
BEGIN
UPDATE notifications
SET sent_to_slack = 'Y'
WHERE notification_id = p_notification_id;
COMMIT;
END mark_notification_sent;
/

