-- implicit cursor to change the description row by row
CREATE OR REPLACE PROCEDURE descriptions_lowercase_by_row AS
BEGIN
FOR job IN (SELECT job_id, description FROM vacant_jobs) LOOP
UPDATE vacant_jobs
SET description = to_lowercase(job.description)
WHERE job_id = job.job_id;
END LOOP;

COMMIT;
END descriptions_lowercase_by_row;
/

