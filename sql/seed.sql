-- function to convert job description to lower case (custom)
CREATE OR REPLACE FUNCTION to_lowercase (p_text IN VARCHAR2)
RETURN VARCHAR2
AS
BEGIN
-- 'translate' replaces every character from the top to the corresponding character at the bottom
RETURN TRANSLATE(p_text,
                 'ABCDEFGHIJKLMNOPQRSTUVWXYZ',
                 'abcdefghijklmnopqrstuvwxyz');
END to_lowercase;
/

-- procedure to insert a new update record in the notifications table
CREATE OR REPLACE PROCEDURE update_notification (p_job_id IN NUMBER, p_job_name IN VARCHAR2,p_description IN VARCHAR2)
AS
BEGIN
INSERT INTO notifications (type, message, job_id)
VALUES ('update', '[' || p_job_name || '] ' || p_description, p_job_id);
END update_notification;
/

-- creating a trigger to change the description from upper case to lower case
CREATE OR REPLACE TRIGGER vacant_jobs_description_update_trigger
BEFORE UPDATE OF description ON vacant_jobs -- before is used here since we are modifying and 'after' is used for reading only
    FOR EACH ROW
BEGIN
  :NEW.description := to_lowercase(:NEW.description);
END vacant_jobs_description_update_trigger;
/

-- implement the changes in the notifications table
CREATE OR REPLACE TRIGGER notifications_update_trigger
AFTER UPDATE OF description ON vacant_jobs
    FOR EACH ROW
BEGIN
  update_notification(:OLD.job_id, :NEW.job_name, :NEW.description);
END notifications_update_trigger;
/

