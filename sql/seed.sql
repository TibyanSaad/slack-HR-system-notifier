-- IMPLICIT CURSOR TO KEEP ONLY THE LASTEST NOTIFICATION AND TAKE THE COUNT OF JOB APPLICANTS
CREATE OR REPLACE PROCEDURE minutely_notification_roundup AS
BEGIN
FOR job IN (SELECT job_id FROM vacant_jobs) LOOP

DELETE FROM notifications WHERE job_id = job.job_id
                            AND notification_id < (SELECT MAX(notification_id) FROM notifications WHERE job_id = job.job_id);

UPDATE notifications SET number_of_applicants = (SELECT COUNT(*) FROM job_applications WHERE job_id = job.job_id)
WHERE job_id = job.job_id;

END LOOP;

COMMIT;
END minutely_notification_roundup;
/

-- JOB TO CALL THE CURSOR EVERY 24 HOURS
BEGIN
  DBMS_SCHEDULER.CREATE_JOB(
    JOB_NAME        => 'DAILY_NOTIFICATION_REDUCTION_AND_APPLICANT_COUNT_JOB',
    JOB_TYPE        => 'PLSQL_BLOCK',
    JOB_ACTION      => 'BEGIN minutely_notification_roundup; END;',
    REPEAT_INTERVAL => 'FREQ=HOURLY; INTERVAL=24',
    START_DATE      => systimestamp,
    ENABLED         => TRUE
  );
END;
/

