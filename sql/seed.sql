-- Part C
-- procedure to add all the records in vacant_jobs table to jobs_posting_archive table
CREATE OR REPLACE PROCEDURE archive_vacant_jobs AS
BEGIN
INSERT INTO jobs_posting_archive (job_id, job_name, description, posted_at, expires_at)
SELECT job_id, job_name, description, posted_at, expires_at FROM vacant_jobs
                                                                     MINUS
SELECT job_id, job_name, description, posted_at, expires_at FROM jobs_posting_archive;

COMMIT;
END archive_vacant_jobs;
/

-- procedure to delete jobs from vacant_jobs table if they become inactive
CREATE OR REPLACE PROCEDURE REMOVE_INACTIVE_JOBS AS
BEGIN
DELETE FROM vacant_jobs WHERE isActive = 'N';
COMMIT;
END REMOVE_INACTIVE_JOBS;
/

--procedure to check if the job is active or not and set isActive to N if not
CREATE OR REPLACE PROCEDURE check_job_is_active AS
BEGIN
UPDATE vacant_jobs SET isActive = 'N' WHERE expires_at <= systimestamp AND isActive = 'Y';
COMMIT;
END check_job_is_active;
/

