-- Creating the tables
--  Table 1: VACANT_JOBS
CREATE TABLE vacant_jobs (
  job_id       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  job_name     VARCHAR2(150) NOT NULL,
  description  VARCHAR2(4000),
  posted_at    TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  expires_at   TIMESTAMP NOT NULL,
  isActive     CHAR(1) DEFAULT 'Y' NOT NULL
    CONSTRAINT ck_vacant_jobs_isactive CHECK (isActive IN ('Y','N'))
);


-- Table 2: NOTIFICATIONS
CREATE TABLE notifications (
  notification_id      NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  type                 VARCHAR2(20) NOT NULL
    CONSTRAINT ck_notification_type CHECK (type IN ('new post','update','application')),
  message              VARCHAR2(4000) NOT NULL,
  created_at           TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  number_of_applicants NUMBER DEFAULT NULL,
  job_id               NUMBER NOT NULL,
    CONSTRAINT fk_notification_job FOREIGN KEY (job_id) REFERENCES vacant_jobs (job_id)
);


-- Table 3: JOB_APPLICATIONS
CREATE TABLE job_applications (
  application_id  NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  applicant_email VARCHAR2(255) NOT NULL,
  applied_at      TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  job_id          NUMBER NOT NULL,
    CONSTRAINT fk_application_job FOREIGN KEY (job_id) REFERENCES vacant_jobs (job_id)
);


-- Table 4: JOBS_POSTING_ARCHIVE
CREATE TABLE jobs_posting_archive (
  job_id       NUMBER PRIMARY KEY,
  job_name     VARCHAR2(150) NOT NULL,
  description  VARCHAR2(4000),
  posted_at    TIMESTAMP NOT NULL,
  expires_at   TIMESTAMP NOT NULL
);

