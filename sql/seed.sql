-- Part A
-- new job posting procedure
CREATE OR REPLACE PROCEDURE new_post_notification (p_job_id IN NUMBER, p_job_name IN VARCHAR2, p_description IN VARCHAR2)
AS
BEGIN
INSERT INTO notifications (type, message, job_id) VALUES ('new post', '[' || p_job_name || '] ' || p_description, p_job_id);
END new_post_notification;
/

-- TRIGGER TO START THE register_notification_trigger PROCEDURE ON INSERTION
CREATE OR REPLACE TRIGGER register_notification_trigger
AFTER INSERT ON vacant_jobs
FOR EACH ROW
BEGIN
  new_post_notification(:NEW.job_id, :NEW.job_name, :NEW.description);
END register_notification_trigger;
/

