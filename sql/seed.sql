-- PROCEDURE TO INSERT INTO NOTIFICATIONS TABLE IF AN APPLICATION IS RECIEVED
CREATE OR REPLACE PROCEDURE application_notification (p_job_id IN NUMBER, p_applicant_email IN VARCHAR2)
AS
  v_job_name    VARCHAR2(150);
  v_description VARCHAR2(4000);
BEGIN
SELECT job_name, description INTO v_job_name, v_description
FROM vacant_jobs
WHERE job_id = p_job_id;

INSERT INTO notifications (type, message, job_id)
VALUES ('application', '[' || v_job_name || '] ' || p_applicant_email || ' applied', p_job_id);
END application_notification;
/

-- trigger that causes any insert into job_applications table to be inserted into the notifications table
CREATE OR REPLACE TRIGGER application_notification_trigger
AFTER INSERT ON job_applications
FOR EACH ROW
BEGIN
  application_notification(:NEW.job_id, :NEW.applicant_email);
END application_notification_trigger;
/

